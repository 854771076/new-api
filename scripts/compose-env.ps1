# scripts/compose-env.ps1
# Makes sure the compose files get the secrets they require.
#
# The compose files refuse to start without REDIS_PASSWORD and POSTGRES_PASSWORD
# (no default password is baked into the repository). docker compose reads the
# repository-local .env file for interpolation, so the passwords are generated
# once and kept there: stable across restarts, and never committed (.env is
# gitignored).
#
# Dot-source it and call Initialize-ComposeSecrets before running compose:
#   . "$PSScriptRoot\compose-env.ps1"
#   Initialize-ComposeSecrets -RepoRoot $repoRoot

function New-LocalSecret {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return -join ($bytes | ForEach-Object { $_.ToString('x2') })
}

function Initialize-ComposeSecrets {
    param([Parameter(Mandatory = $true)][string]$RepoRoot)

    $envFile = Join-Path $RepoRoot '.env'
    $existing = @{}
    if (Test-Path $envFile) {
        foreach ($line in Get-Content $envFile) {
            if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') {
                $existing[$Matches[1]] = $Matches[2]
            }
        }
    }

    $added = @()
    foreach ($name in @('REDIS_PASSWORD', 'POSTGRES_PASSWORD')) {
        if ([string]::IsNullOrWhiteSpace($existing[$name])) {
            $existing[$name] = New-LocalSecret
            $added += $name
        }
        Set-Item -Path "env:$name" -Value $existing[$name]
    }

    if ($added.Count -gt 0) {
        $lines = @('', '# Generated by scripts/compose-env.ps1 for local compose runs')
        foreach ($name in $added) {
            $lines += "$name=$($existing[$name])"
        }
        Add-Content -Path $envFile -Value $lines
        Write-Host "==> Generated $envFile with: $($added -join ', ')" -ForegroundColor Cyan
    }
}
