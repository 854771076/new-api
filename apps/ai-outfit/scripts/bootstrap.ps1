#!/usr/bin/env pwsh
# scripts/bootstrap.ps1 — auto-configure new-api OAuth + Supabase external app
# Depends on: newapi-cli (already logged in), supabase CLI, bun
# Usage: from project root: ./scripts/bootstrap.ps1 -ProjectName "AI Outfit"
# Flow: probe newapi-cli login -> probe existing outfit-demo OAuth app (reuse) ->
#       supabase link -> db push -> custom:newapi provider check/create ->
#       write .env.local -> admin SQL (UUID mapping)

param(
  [string]$ProjectName = "AI Outfit",
  [string]$ClientIdOverride = "",   # manual OAuth app id; empty = reuse outfit-demo
  [string]$PackRoot = ""            # asset pack root; empty = skip seed
)

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location (Join-Path $scriptDir "..")

function Write-Step($msg) { Write-Host "`n>> $msg" -ForegroundColor Cyan }
function Write-OK($msg)  { Write-Host "   OK  $msg" -ForegroundColor Green }
function Write-Warn($msg){ Write-Host "   WARN $msg" -ForegroundColor Yellow }
function Write-Err($msg) { Write-Host "   ERR  $msg" -ForegroundColor Red }

# --- 1. Toolchain ---
Write-Step "Check toolchain"
foreach ($cmd in @("newapi-cli", "supabase", "bun")) {
  $found = Get-Command $cmd -ErrorAction SilentlyContinue
  if ($found) { Write-OK "$cmd : $($found.Source)" } else { Write-Err "$cmd not found"; exit 1 }
}

# --- 2. newapi-cli auth status ---
Write-Step "newapi-cli auth status"
& newapi-cli auth status 2>&1 | ForEach-Object { Write-Host "   $_" }
if ($LASTEXITCODE -ne 0) { Write-Err "Run newapi-cli auth login first"; exit 1 }

# --- 3. Get self user + OAuth apps ---
Write-Step "Get new-api user + OAuth apps"
$self = (& newapi-cli api GET "/api/user/self" 2>&1 | Out-String | ConvertFrom-Json)
$apps = (& newapi-cli api GET "/api/oauth-apps" 2>&1 | Out-String | ConvertFrom-Json)
Write-OK "User: $($self.username) (id=$($self.id), role=$($self.role))"

$selectedClientId = $ClientIdOverride
$supabaseProjectRef = $null

if (-not $selectedClientId) {
  $existing = @($apps | Where-Object { $_.public_client -eq $true -and $_.supabase_project_ref })
  if ($existing.Count -gt 0) {
    $pick = $existing[0]
    $selectedClientId = $pick.client_id
    $supabaseProjectRef = $pick.supabase_project_ref
    Write-OK "Reuse OAuth app: $($pick.name) -> client_id=$selectedClientId"
    Write-OK "Bound Supabase project: $supabaseProjectRef"
  } else {
    Write-Warn "No public OAuth app with Supabase found; create one in new-api dashboard first"
    exit 1
  }
}

# --- 4. Supabase link ---
Write-Step "Supabase link --project-ref $supabaseProjectRef"
& supabase link --project-ref $supabaseProjectRef 2>&1 | ForEach-Object { Write-Host "   $_" }

# --- 5. Supabase API keys ---
Write-Step "Fetch Supabase API keys"
$keysText = (& supabase projects api-keys 2>&1 | Out-String)
# Match "anon     | <jwt>" and "service_role | <jwt>" from the column table output.
# Trim leading/trailing pipe + whitespace on each line.
$anonKey = ($keysText -split "`n" | Where-Object { $_ -match '^\s*anon\s+\|' } | Select-Object -First 1) -replace '^\s*anon\s+\|\s*', '' -replace '\s+\|.*', ''
$serviceRoleKey = ($keysText -split "`n" | Where-Object { $_ -match '^\s*service_role\s+\|' } | Select-Object -First 1) -replace '^\s*service_role\s+\|\s*', '' -replace '\s+\|.*', ''
$serverUrl = (& newapi-cli auth status 2>&1 | Out-String | ConvertFrom-Json).server
if (-not $serverUrl) { Write-Err "Cannot determine new-api server URL"; exit 1 }

Write-OK "Gateway: $serverUrl"
Write-OK "Anon key (len=$($anonKey.Length))"
Write-OK "Service_role key (len=$($serviceRoleKey.Length))"

# --- 6. Write .env.local ---
Write-Step "Write .env.local"
$envContent = @"
# auto-generated by scripts/bootstrap.ps1
NEXT_PUBLIC_SUPABASE_URL=https://$supabaseProjectRef.supabase.co
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anonKey
SUPABASE_SECRET_KEY=$serviceRoleKey
NEXT_PUBLIC_GATEWAY_BASE_URL=$serverUrl
GATEWAY_PUBLIC_URL=$serverUrl
NEXT_PUBLIC_GATEWAY_CLIENT_ID=$selectedClientId
APP_ORIGIN=http://localhost:3000
INITIAL_ADMIN_SUB=$($self.id)
"@
Set-Content -Path ".env.local" -Value $envContent -Encoding utf8
Write-OK ".env.local written"

# --- 7. db push ---
Write-Step "supabase db push --remote --yes"
& supabase db push --remote --yes 2>&1 | ForEach-Object { Write-Host "   $_" }

# --- 8. Check custom:newapi provider ---
# Note: endpoint is /auth/v1/admin/custom-providers (plural), not /providers
# PUT /auth/v1/admin/config is deprecated (returns 404 in modern Supabase);
# localhost redirects are auto-allowed.
Write-Step "Check Supabase custom:newapi provider"
$customProvidersUrl = "https://$supabaseProjectRef.supabase.co/auth/v1/admin/custom-providers"
$authHeaders = @{
  apikey = $serviceRoleKey
  Authorization = "Bearer $serviceRoleKey"
}
try {
  $providers = (Invoke-RestMethod -Uri $customProvidersUrl -Headers $authHeaders -UseBasicParsing).providers
  $custom = @($providers | Where-Object { $_.identifier -eq "custom:newapi" })[0]
  if ($custom) {
    Write-OK "custom:newapi exists (issuer=$($custom.issuer), pkce=$($custom.pkce_enabled))"
    $needRecreate = $custom.issuer -ne $serverUrl -or -not $custom.pkce_enabled -or -not $custom.email_optional
    if ($needRecreate) {
      Write-Warn "provider mismatch; delete + recreate"
      Invoke-RestMethod -Uri "$customProvidersUrl/custom:newapi" -Method DELETE -Headers $authHeaders -UseBasicParsing | Out-Null
      $custom = $null
    }
  }
  if (-not $custom) {
    Write-Step "Create custom:newapi provider"
    $body = @{
      provider_type = "oidc"; identifier = "custom:newapi"; name = "new-api"
      issuer = $serverUrl; client_id = $selectedClientId; client_secret = "ignored-by-public-client"
      scopes = @("openid","profile","email","api:read","api:write")
      pkce_enabled = $true; email_optional = $true
    } | ConvertTo-Json -Depth 5
    Invoke-RestMethod -Uri $customProvidersUrl -Method POST -Headers ($authHeaders + @{ "Content-Type" = "application/json" }) -Body $body -UseBasicParsing | Out-Null
    Write-OK "provider created"
  }
} catch {
  Write-Err "provider check/create failed: $_"
}

# --- 9. Authorize endpoint smoke test ---
Write-Step "Authorize endpoint smoke test"
$authUrl = "https://$supabaseProjectRef.supabase.co/auth/v1/authorize?provider=custom:newapi&redirect_to=http://localhost:3000/auth/callback"
try {
  $resp = Invoke-WebRequest -Uri $authUrl -Headers $authHeaders -MaximumRedirection 0 -UseBasicParsing -ErrorAction Stop
  Write-OK "authorize -> $($resp.StatusCode), redirect=$($resp.Headers.Location)"
} catch {
  Write-Warn "authorize test failed: $($_.Exception.Message)"
}

# --- 10. Admin bootstrap ---
# new-api OAuth sub is an integer user id (stored in auth.users.raw_user_meta_data.sub).
# app_admins.user_id must be auth.users.id (UUID). Query to map them.
Write-Step "Admin bootstrap: resolve auth.users UUID for sub=$($self.id)"
$uuidQuery = "SELECT id::text FROM auth.users WHERE raw_user_meta_data->>'sub' = '$($self.id)' AND raw_app_meta_data->>'provider' = 'custom:newapi' LIMIT 1;"
$uuidResult = (& supabase db query --remote --yes $uuidQuery 2>&1 | Out-String)
Write-Host "   $uuidResult"
# Extract UUID from psql table output
$uuidPattern = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
$adminUuid = ($uuidResult | Select-String -Pattern $uuidPattern -AllMatches).Matches.Value
if ($adminUuid) {
  Write-OK "auth.users UUID: $adminUuid"
  $adminInsert = & supabase db query --remote --yes "INSERT INTO public.app_admins (user_id, role, created_at) VALUES ('$adminUuid'::uuid, 'owner', now()) ON CONFLICT (user_id) DO NOTHING RETURNING id, role;" 2>&1 | Out-String
  Write-Host "   $adminInsert"
  # Update .env.local INITIAL_ADMIN_SUB to real UUID
  $envPath = ".env.local"
  if (Test-Path $envPath) {
    $content = Get-Content $envPath -Raw
    $content = $content -replace "INITIAL_ADMIN_SUB=.*", "INITIAL_ADMIN_SUB=$adminUuid"
    Set-Content -Path $envPath -Value $content -Encoding utf8
    Write-OK ".env.local INITIAL_ADMIN_SUB -> UUID"
  }
} else {
  Write-Warn "No auth.users row found for sub=$($self.id). Admin must log in first (custom:newapi)"
  Write-Warn "Then run manually: supabase db query --remote `"INSERT INTO public.app_admins (user_id, role, created_at) VALUES ('<uuid>'::uuid, 'owner', now());`""
}

# --- 11. Asset seed (optional) ---
if ($PackRoot) {
  Write-Step "Asset seed: bun run scripts/seed-assets.ts --pack-root $PackRoot --client-id $selectedClientId"
  Push-Location (Join-Path $scriptDir "..")
  & bun.cmd run "scripts/seed-assets.ts" --pack-root $PackRoot --client-id $selectedClientId 2>&1 | ForEach-Object { Write-Host "   $_" }
  Pop-Location
}

Write-Host "`n*** bootstrap done ***" -ForegroundColor Magenta
Write-Host "  1. bun run dev"
Write-Host "  2. http://localhost:3000/login -> OAuth flow"
Write-Host "  3. http://localhost:3000/admin (need login + admin bootstrap SQL applied)"
Write-Host "  4. Without -PackRoot: bun run scripts/seed-assets.ts --pack-root <path> --client-id $selectedClientId"
